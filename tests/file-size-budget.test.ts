import test from "node:test";
import assert from "node:assert/strict";
import { readdirSync, readFileSync, statSync } from "node:fs";
import { join } from "node:path";

/**
 * Tamanho é um sinal de manutenção, NÃO um portão de aprovação.
 *
 * - Até 400 linhas: tamanho preferencial.
 * - De 401 a 800: atenção; revisar apenas quando houver ganho de coesão.
 * - Acima de 800: revisão arquitetural recomendada, sem falhar o CI por linhas.
 * - Fontes geradas: classificadas separadamente; não refatorar manualmente.
 *
 * Uma responsabilidade coesa pode ocupar mais de 400 linhas. Fragmentar apenas
 * para reduzir a contagem prejudica a leitura e não corrige acoplamento.
 * Erros de compilação, fronteiras arquiteturais e regressões ainda reprovam
 * em seus próprios testes. Ver docs/adr/0013-decomposicao-do-game.md.
 */
export const PREFERRED_LINES = 400;
export const REVIEW_LINES = 800;
export type FileSizeAdvisory = "preferred" | "attention" | "review" | "generated";

/** Política pura: usada também pelos testes de fronteira, independente do filesystem. */
export function classifyFileSize(lines: number, generated = false): FileSizeAdvisory {
  if (!Number.isSafeInteger(lines) || lines < 1)
    throw new RangeError("O número de linhas deve ser um inteiro positivo");
  if (generated) return "generated";
  if (lines <= PREFERRED_LINES) return "preferred";
  return lines <= REVIEW_LINES ? "attention" : "review";
}

const ROOTS = ["src", "server/src"];
const pathsIn = (dir: string): string[] => readdirSync(dir).flatMap(name => {
  const path = join(dir, name);
  return statSync(path).isDirectory() ? pathsIn(path)
    : path.endsWith(".ts") && !path.endsWith(".d.ts") ? [path.replaceAll("\\", "/")] : [];
});
const sources = ROOTS.flatMap(pathsIn).sort();
const lineCount = (source: string): number => source.replace(/\n$/, "").split("\n").length;
/** Cabeçalho inequívoco. Tabelas escritas à mão continuam visíveis no relatório. */
const generatedHeader = (source: string): boolean =>
  /(?:@generated|<auto-generated\b|gerado automaticamente|automatically generated)/i
    .test(source.split("\n").slice(0, 8).join("\n"));

test("tamanho: avisos não viram erro nas fronteiras 400/800", () => {
  assert.equal(classifyFileSize(1), "preferred");
  assert.equal(classifyFileSize(400), "preferred");
  assert.equal(classifyFileSize(401), "attention");
  assert.equal(classifyFileSize(800), "attention");
  assert.equal(classifyFileSize(801), "review");
  assert.equal(classifyFileSize(2000), "review");
  assert.equal(classifyFileSize(5000, true), "generated");
  assert.throws(() => classifyFileSize(0), RangeError);
  assert.throws(() => classifyFileSize(Number.NaN), RangeError);
});

test("tamanho: examina TypeScript, relata arquivos grandes e nunca bloqueia só por linhas", t => {
  assert.ok(sources.length > 0, "Nenhuma fonte TypeScript foi encontrada");
  const counts: Record<FileSizeAdvisory, number> = {
    preferred: 0, attention: 0, review: 0, generated: 0,
  };
  for (const path of sources) {
    const source = readFileSync(path, "utf8");
    const lines = lineCount(source);
    const category = classifyFileSize(lines, generatedHeader(source));
    counts[category]++;
    if (category === "attention")
      t.diagnostic(`AVISO (não bloqueante): ${path} (${lines} linhas) — manter responsabilidade coesa; dividir somente se melhorar a manutenção`);
    if (category === "review")
      t.diagnostic(`REVISÃO RECOMENDADA (não bloqueante): ${path} (${lines} linhas) — avaliar acoplamento, testes e separação por responsabilidade`);
  }
  t.diagnostic(`Inventário TypeScript: ${sources.length} arquivos; ${counts.preferred} preferenciais, ${counts.attention} avisos, ${counts.review} revisões recomendadas, ${counts.generated} gerados`);
  assert.equal(Object.values(counts).reduce((sum, count) => sum + count, 0), sources.length,
    "Cada arquivo fonte precisa ser classificado exatamente uma vez");
});
